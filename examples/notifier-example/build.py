"""Generate bindings from an SDK snapshot and a POSIX executable launcher."""

import argparse
from pathlib import Path
import re
import shlex
import subprocess
import sys


def main():
    example = Path(__file__).resolve().parent
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--sdk-root", type=Path, default=example.parents[1])
    args = parser.parse_args()
    sdk = args.sdk_root.resolve()

    # Stamp the contract from the SAME SDK snapshot as the protobuf sources.
    # Do not lower it by hand just because this plugin uses only two methods.
    contract_source = (sdk / "plugin/contract.go").read_text()
    match = re.search(r"^const ContractVersion = (\d+)$", contract_source, re.MULTILINE)
    if match is None:
        parser.error("cannot read ContractVersion from the selected SDK")

    generated = example / "_generated"
    generated.mkdir(exist_ok=True)
    subprocess.run(
        [
            sys.executable, "-m", "grpc_tools.protoc", f"-I{sdk}",
            f"--python_out={generated}", f"--grpclib_python_out={generated}",
            f"--plugin=protoc-gen-grpclib_python={Path(sys.executable).parent / 'protoc-gen-grpclib_python'}",
            "plugin/proto/provisioner.proto",  # Shared ConfigField messages.
            "plugin/proto/notifier.proto",
        ],
        cwd=sdk,
        check=True,
    )
    (generated / "contract.py").write_text(
        f"# Generated by build.py; do not edit.\nCONTRACT_VERSION = {match[1]}\n"
    )

    # An absolute interpreter survives the host's scrubbed environment and does
    # not require an activated venv or PYTHONPATH. Do NOT resolve this symlink:
    # venv/bin/python must keep its venv identity instead of becoming /usr/bin/python.
    python = Path(sys.executable).absolute()
    launcher = example / "dist/notifier-python-example"
    launcher.parent.mkdir(exist_ok=True)
    launcher.write_text(
        "#!/bin/sh\n"
        f"exec {shlex.quote(str(python))} -B -u "
        f"{shlex.quote(str(example / 'main.py'))} \"$@\"\n"
    )
    launcher.chmod(0o755)
    print(f"Built {launcher}")


if __name__ == "__main__":
    main()
